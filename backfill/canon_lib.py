def canon(s):
    n = norm(s)
    n = XW.get(n, n)
    n = re.sub(r'\bAHAFO AND\b', 'AHAFO ANO', n)
    n = re.sub(r'\bATWIWA\b', 'ATWIMA', n)
    n = re.sub(r'\bASIKUMA OD\w+ BRAKWA\b|\bASIKUMA OBOBEN BRAKWA\b', 'ASIKUMA ODOBEN BRAKWA', n)
    # The three towns are written in either order on different sources
    # (EC sheets say "Asene Manso Akroso"); fix on the panel's dominant form.
    n = re.sub(r'\bASENE MANSO AKROSO\b', 'ASENE AKROSO MANSO', n)
    return XW.get(n, n)
