"""Shared canonicalization for Ghana constituency names (project crosswalk)."""
import re, unicodedata

def norm(s):
    s = str(s).upper().strip()
    s = unicodedata.normalize('NFKD', s)
    s = re.sub(r"[\/\-\.\,\(\)\']", ' ', s)
    return re.sub(r'\s+', ' ', s).strip()

